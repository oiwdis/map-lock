    static func capital(of name: String) -> String? { capitals[name]?.first }

    /// Regional-indicator emoji for a country, or nil if unknown.
    static func flagEmoji(for name: String) -> String? {
        guard let code = iso2[name], code.count == 2 else { return nil }
        let base: UInt32 = 0x1F1E6
        var s = ""
        for u in code.uppercased().unicodeScalars {
            let v = u.value
            guard v >= 65, v <= 90, let scalar = UnicodeScalar(base + (v - 65)) else { return nil }
            s.unicodeScalars.append(scalar)
        }
        return s
    }

    /// Every accepted capital spelling, already normalized for AnswerChecker.
    static func capitalForms(of name: String) -> Set<String> {
        Set((capitals[name] ?? []).map { AnswerChecker.normalize($0) }.filter { !$0.isEmpty })
    }
